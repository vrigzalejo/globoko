/**
 * Stick figures and bright galaxies.
 * Star rows are J2000 right ascension in hours, declination in degrees, and magnitude.
 * A trailing `true` marks a corner borrowed from the neighboring figure.
 */

function unitEqj(raHours, decDeg) {
  const ra = raHours * (Math.PI / 12);
  const dec = decDeg * (Math.PI / 180);
  const cosDec = Math.cos(dec);
  return [cosDec * Math.cos(ra), cosDec * Math.sin(ra), Math.sin(dec)];
}

function cross(a, b) {
  return [
    a[1] * b[2] - a[2] * b[1],
    a[2] * b[0] - a[0] * b[2],
    a[0] * b[1] - a[1] * b[0],
  ];
}

function normalize(vector) {
  const span = Math.hypot(vector[0], vector[1], vector[2]) || 1;
  return [vector[0] / span, vector[1] / span, vector[2] / span];
}

const GALACTIC_CENTER = unitEqj(17.761122, -28.936175);
const GALACTIC_NORTH = unitEqj(12.856667, 27.12825);
const GALACTIC_Y = normalize(cross(GALACTIC_NORTH, GALACTIC_CENTER));
const GALACTIC_X = normalize(cross(GALACTIC_Y, GALACTIC_NORTH));

/** Galactic longitude and latitude, in degrees, to J2000 equatorial hours and degrees. */
export function galacticToEquatorial(longitude, latitude) {
  const l = longitude * (Math.PI / 180);
  const b = latitude * (Math.PI / 180);
  const cosB = Math.cos(b);
  const gx = cosB * Math.cos(l);
  const gy = cosB * Math.sin(l);
  const gz = Math.sin(b);
  const x = GALACTIC_X[0] * gx + GALACTIC_Y[0] * gy + GALACTIC_NORTH[0] * gz;
  const y = GALACTIC_X[1] * gx + GALACTIC_Y[1] * gy + GALACTIC_NORTH[1] * gz;
  const z = GALACTIC_X[2] * gx + GALACTIC_Y[2] * gy + GALACTIC_NORTH[2] * gz;
  const dec = Math.asin(Math.max(-1, Math.min(1, z))) * (180 / Math.PI);
  let ra = Math.atan2(y, x) * (12 / Math.PI);
  if (ra < 0) ra += 24;
  return { ra, dec };
}

export function milkyWayBands() {
  const belts = [
    { latitude: 0, width: 22, alpha: 0.5 },
    { latitude: 8, width: 12, alpha: 0.22 },
    { latitude: -8, width: 12, alpha: 0.22 },
  ];
  return belts.map((belt) => {
    const samples = [];
    for (let step = 0; step <= 120; step += 1) {
      samples.push(galacticToEquatorial((step / 120) * 360, belt.latitude));
    }
    return { ...belt, samples };
  });
}

